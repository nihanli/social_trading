NLP_ERRORS = Counter(
    "nlp_errors_total",
    "Errors in NLP pipeline processing",
    ["stage"],   # "bot_filter", "ticker_extract", "vader", "finbert"
)

# ── Signal metrics ────────────────────────────────────────────────────────────

