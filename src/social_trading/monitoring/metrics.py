"""
Central Prometheus metrics registry for the social trading system.

All services import from this module — each process registers its metrics
once at startup. The HTTP /metrics endpoint is exposed on port 8000 per
service (Prometheus scrapes each container individually).

Design reference: docs/design/13-monitoring-observability.md

Usage:
    from social_trading.monitoring.metrics import (
        start_metrics_server,
        POSTS_INGESTED, SIGNALS_GENERATED, ...
    )
    start_metrics_server(port=8000)

    # In hot path:
    POSTS_INGESTED.labels(source="twitter", ticker="AAPL").inc()
"""
from __future__ import annotations

import logging

from prometheus_client import (
    Counter,
    Gauge,
    Histogram,
    start_http_server,
)

logger = logging.getLogger(__name__)

# ── Ingestion metrics ─────────────────────────────────────────────────────────

