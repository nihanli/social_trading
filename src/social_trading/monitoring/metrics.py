# ── Circuit breaker state constants ──────────────────────────────────────────

CIRCUIT_STATE_VALUES = {
    "NORMAL": 0,
    "REDUCED_50": 1,
    "DAILY_HALT": 2,
    "FULL_HALT": 3,
}


# ── Helpers ───────────────────────────────────────────────────────────────────

def start_metrics_server(port: int = 8000) -> None:
    """
    Start the Prometheus HTTP metrics server on the given port.
    Call once at service startup, before entering the main loop.
    Idempotent — logs a warning and continues if the port is already bound.
    """
    try:
        start_http_server(port)
        logger.info("Prometheus metrics server started on :%d/metrics", port)
    except OSError as exc:
        logger.warning("Could not start metrics server on port %d: %s", port, exc)


def set_circuit_breaker_state(state_name: str) -> None:
    """Update CIRCUIT_BREAKER_STATE gauge from a state name string."""
    value = CIRCUIT_STATE_VALUES.get(state_name, 0)
    CIRCUIT_BREAKER_STATE.set(value)
